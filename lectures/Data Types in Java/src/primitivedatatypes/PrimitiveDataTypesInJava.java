package primitivedatatypes;

public class PrimitiveDataTypesInJava {
    public static void main(String[] args) {

        // To store very small whole numbers
        byte age = 12;

        // To store small whole numbers
        short villagePopulation = 12000;

        // Most commonly used integer type
        int bookCount = 10;

        // To store very large whole numbers
        long bankTransactionId = 1000_0222_2211_1113L;

        // To store decimal numbers with less precision
        float temperature = 36.5f;

        // Default and preferred type for decimal values
        double bankBalance = 10000000.11643534545;

        // To store single character
        char grade = 'A';

        // To Stores logical values true or false
        boolean isUserLoggedIn = true;

    }
}
